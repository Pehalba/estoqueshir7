/** Busca artes por texto livre (posição + nome da arte) e productId opcional. */
export function findPersonalizationArt({ text = '', productId = '' } = {}) {
  const q = String(text).toLowerCase().normalize('NFD').replace(/\p{M}/gu, '');
  if (!q.trim()) return null;

  const scored = PERSONALIZATION_ARTS.map((art) => {
    let score = 0;
    const label = art.label.toLowerCase().normalize('NFD').replace(/\p{M}/gu, '');
    const place = art.placement.toLowerCase().normalize('NFD').replace(/\p{M}/gu, '');

    if (productId && art.productIds.includes(productId)) score += 5;
    if (q.includes(label)) score += 8;
    else {
      const tokens = label.split(/[^a-z0-9]+/).filter((t) => t.length > 2);
      score += tokens.filter((t) => q.includes(t)).length * 2;
    }
    if (art.placementAliases.some((a) => q.includes(a.normalize('NFD').replace(/\p{M}/gu, '')))) score += 4;
    else if (q.includes(place)) score += 3;
    return { art, score };
  }).filter((x) => x.score > 0);

  scored.sort((a, b) => b.score - a.score);
  return scored[0]?.art || null;
}
